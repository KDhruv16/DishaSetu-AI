import mongoose from 'mongoose';

const careerInterestSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    description: {
      type: String,
      trim: true,
    },
    isActive: {
      type: Boolean,
      default: true,
    },
    order: {
      type: Number,
      default: 0,
    },
  },
  { timestamps: true }
);

const CareerInterest = mongoose.model('CareerInterest', careerInterestSchema);
export default CareerInterest;
