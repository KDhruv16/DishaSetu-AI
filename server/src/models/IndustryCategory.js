import mongoose from 'mongoose';

const industryCategorySchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    description: {
      type: String,
      trim: true,
    },
    isActive: {
      type: Boolean,
      default: true,
    },
    displayOrder: {
      type: Number,
      default: 0,
    },
  },
  { timestamps: true }
);

const IndustryCategory = mongoose.model('IndustryCategory', industryCategorySchema);
export default IndustryCategory;
